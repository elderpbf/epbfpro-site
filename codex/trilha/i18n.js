const DICTS = { 'pt-BR': pt, en };
let active = 'pt-BR';

export function t(key) { const d = DICTS[active] || {}; return key in d ? d[key] : key; }
export function setLang(l) { if (DICTS[l]) active = l; }
export function languages() { return Object.keys(DICTS); }
